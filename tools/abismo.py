def iso(blocks, s=5, y_max=78):
    solid = {(x, y, z): b for x, y, z, b in blocks if y <= y_max}
    xs = [k[0] for k in solid]
    zs = [k[2] for k in solid]
    ys = [k[1] for k in solid]
    x0, z0, y0 = min(xs), min(zs), min(ys)
    W = (max(xs) - x0 + max(zs) - z0 + 4) * s * 2
    H = (max(xs) - x0 + max(zs) - z0 + 4) * s + (max(ys) - y0 + 4) * s * 2
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    ox, oy = (max(zs) - z0 + 2) * s * 2, (max(ys) - y0 + 2) * s * 2

    def P(x, y, z):
        return (ox + ((x - x0) - (z - z0)) * s * 2, oy + ((x - x0) + (z - z0)) * s - (y - y0) * s * 2)

    for (x, y, z), b in sorted(solid.items(), key=lambda kv: (kv[0][0] + kv[0][2], kv[0][1])):
        c = hx(BLOCK_COLORS.get(b, "#ff00ff"))
        if b in THIN:
            d.polygon([P(x + .3, y + .7, z + .3), P(x + .7, y + .7, z + .3), P(x + .7, y + .7, z + .7), P(x + .3, y + .7, z + .7)], fill=c)
            continue
        if solid.get((x, y + 1, z)) not in (None, *THIN) and (x + 1, y, z) in solid and (x, y, z + 1) in solid:
            continue
        d.polygon([P(x + 1, y + 1, z), P(x + 1, y + 1, z + 1), P(x + 1, y, z + 1), P(x + 1, y, z)],
                  fill=tuple(int(k * 0.75) for k in c[:3]) + (255,))
        d.polygon([P(x, y + 1, z + 1), P(x + 1, y + 1, z + 1), P(x + 1, y, z + 1), P(x, y, z + 1)],
                  fill=tuple(int(k * 0.6) for k in c[:3]) + (255,))
        d.polygon([P(x, y + 1, z), P(x + 1, y + 1, z), P(x + 1, y + 1, z + 1), P(x, y + 1, z + 1)], fill=c)
    return img.crop(img.getbbox())


def floor_map(rooms, n, cell=22):
    img = Image.new("RGBA", (n * cell + 2, n * cell + 2), hx("#111114"))
    d = ImageDraw.Draw(img)
    rx0, rz0 = rooms[0]["rx"], rooms[0]["rz"]
    for r in rooms:
        x, y = (r["rx"] - rx0) * cell + 1, (r["rz"] - rz0) * cell + 1
        d.rectangle([x + 2, y + 2, x + cell - 2, y + cell - 2], fill=hx(TYPE_COLORS[r["type"]]))
        if r["arrival"]:
            d.rectangle([x + 4, y + 4, x + 9, y + 9], fill=hx("#9ad0ff"))
        if r["type"] == "escalera":
            d.polygon([(x + 6, y + 8), (x + cell - 6, y + 8), (x + cell // 2, y + cell - 5)], fill=hx("#202024"))
        mid = cell // 2
        for k, (dx, dy) in enumerate(((cell - 1, mid), (0, mid), (mid, cell - 1), (mid, 0))):
            if r["doors"][k] == "wall":
                continue
            w = 4 if r["doors"][k] == "door" else mid - 2
            if k < 2:
                d.rectangle([x + dx - 2, y + mid - w, x + dx + 2, y + mid + w], fill=hx("#c9c9cf"))
            else:
                d.rectangle([x + mid - w, y + dy - 2, x + mid + w, y + dy + 2], fill=hx("#c9c9cf"))
    return img


