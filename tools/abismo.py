def controller(name):
    m = MUTANTS[name]
    if m.get("ranged"):
        return {"initial_state": "default", "states": {
            "default": {"animations": ["move", "move_arms", "idle", "look", "no_arrow"], "blend_transition": 0.2,
                        "transitions": [{"aim": "query.has_target"}]},
            "aim": {"animations": ["move", "idle", "look", "charge"], "blend_transition": 0.2,
                    "transitions": [{"default": "!query.has_target"}]}}}
    to_special = [{"special": f"{ACTION} == 1"}] + ([{"roar": f"{ACTION} == 2"}] if m.get("roar") else [])
    states = {
        "default": {"animations": ["move", "idle", "look"], "blend_transition": 0.2,
                    "transitions": to_special + ([{"attack": "variable.attack_time > 0.0"}] if m.get("attack") else [])},
        "special": {"animations": [m["special"]], "blend_transition": 0.15,
                    "transitions": [{"default": f"{ACTION} == 0 && query.all_animations_finished"}]},
    }
    if m.get("attack"):
        states["attack"] = {"animations": ["move", "look", "attack"], "blend_transition": 0.1,
                            "transitions": to_special + [{"default": "variable.attack_time <= 0.0"}]}
    if m.get("roar"):
        states["roar"] = {"animations": ["roar"], "blend_transition": 0.2,
                          "transitions": [{"default": f"{ACTION} == 0 && query.all_animations_finished"}]}
    return {"initial_state": "default", "states": states}


