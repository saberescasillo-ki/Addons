def style_sheet(mob_assets):
    """The user's reference mutants (top) next to the abyss mutants (bottom)."""
    refs = []
    for name, tex in (("mutant_skeleton", "mutant_skeleton"), ("mutant_stray", "mutant_stray"),
                      ("mutant_bogged", "mutant_bogged"), ("mutant_wither_skeleton", "mutant_wither_skeleton")):
        geo = json.load(open(os.path.join(REFS, f"{name}.geo.json")))
        refs.append(render(geo, Image.open(os.path.join(REFS, f"{tex}.png")).convert("RGBA"), yaw=28, pitch=10, scale=3))
    mine = [render(geo, tex, yaw=28, pitch=10, scale=3) for geo, tex, _ in mob_assets.values()]
    rows = [("Referencia (texturas de entrenamiento)", refs), ("Mutantes del Abismo, mismo estilo", mine)]
    W = max(sum(i.width for i in r) + 30 * len(r) for _, r in rows) + 40
    H = sum(max(i.height for i in r) + 60 for _, r in rows) + 20
    sheet = Image.new("RGBA", (W, H), hx("#0d0f12"))
    d = ImageDraw.Draw(sheet)
    y = 10
    for title, ims in rows:
        d.text((W // 2, y + 14), title, fill=(225, 230, 235, 255), anchor="mm", font=font(18))
        h = max(i.height for i in ims)
        x = (W - sum(i.width for i in ims) - 30 * (len(ims) - 1)) // 2
        for im in ims:
            sheet.alpha_composite(im, (x, y + 40 + h - im.height))
            x += im.width + 30
        y += h + 60
    return sheet


def spawn_table():
    """Markdown table: chance of each mob per floor (for the README)."""
    rows = []
    totals = [sum(weight(s, f) for _, s, _, _ in MOBS) for f in range(3)]
    for mid, s, _, _ in MOBS:
        name = MUTANTS[mid.split(":")[1]]["es"] if mid.startswith(NS) else mid.split(":")[1]
        rows.append(f"| {name} | {s:g} | " + " | ".join(f"{100 * weight(s, f) / totals[f]:.1f} %" for f in range(3)) + " |")
    return "\n".join(["| Mob | Fuerza | Piso 1 | Piso 2 | Piso 3 |", "|---|---|---|---|---|"] + rows)


