def loot_table(name):
    pools = []
    for item_id, lo, hi, chance in MUTANTS[name]["loot"]:
        pool = {"rolls": 1, "entries": [{"type": "item", "name": f"minecraft:{item_id}", "weight": 1,
                                         "functions": [{"function": "set_count", "count": {"min": lo, "max": hi}}]}]}
        if chance < 1:
            pool["conditions"] = [{"condition": "random_chance", "chance": chance}]
        pools.append(pool)
    return {"pools": pools}


