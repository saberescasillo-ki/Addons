def manifests():
    def bp(m):
        m["header"]["version"] = VERSION
        for mod in m["modules"]:
            mod["version"] = VERSION
        m["dependencies"] = [d for d in m["dependencies"] if "module_name" not in d] + [
            {"module_name": "@minecraft/server", "version": "2.11.0"},
            {"module_name": "@minecraft/server-ui", "version": "2.3.0"}]
        for d in m["dependencies"]:
            if "uuid" in d:
                d["version"] = VERSION
    edit(os.path.join(BP, "manifest.json"), bp)

    def rp(m):
        m["header"]["version"] = VERSION
        for mod in m["modules"]:
            mod["version"] = VERSION
        for d in m.get("dependencies", []):
            d["version"] = VERSION
    edit(os.path.join(RP, "manifest.json"), rp)


