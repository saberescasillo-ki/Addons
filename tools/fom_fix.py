def health_groups(ent, base, prefix, event_prefix):
    for i, k in enumerate(HEALTH_STEPS):
        ent["component_groups"][f"{prefix}{i}"] = {"minecraft:health": {"value": round(base * k), "max": round(base * k)}}
    names = [f"{prefix}{i}" for i in range(len(HEALTH_STEPS))]
    for i in range(len(HEALTH_STEPS)):
        ent["events"][f"{event_prefix}{i}"] = {"remove": {"component_groups": [n for n in names if n != f"{prefix}{i}"]},
                                               "add": {"component_groups": [f"{prefix}{i}"]}}


def fix_bosses():
    for ident, info in BOSSES.items():
        path = os.path.join(BP, "entities", info["file"])
        d = load(path)
        ent = d["minecraft:entity"]
        comps = ent["components"]
        info["width"] = round(comps["minecraft:collision_box"]["width"] * comps.get("minecraft:scale", {}).get("value", 1), 2)
        comps["minecraft:attack"]["damage"] = 6
        comps["minecraft:navigation.walk"]["can_break_doors"] = False
        for g in ent["component_groups"].values():
            if "minecraft:attack" in g:
                g["minecraft:attack"]["damage"] = max(2, round(g["minecraft:attack"]["damage"] * MELEE_SCALE))
        base = comps["minecraft:health"]["max"]
        health_groups(ent, base, "xrworks:hp_", "xrworks:set_hp_")
        if info["phase2Event"]:
            p2 = ent["component_groups"]["xrworks:doctor_lantern_phase_2"]
            base2 = p2.pop("minecraft:health")["max"]
            health_groups(ent, base2, "xrworks:hp2_", "xrworks:set_hp2_")
            # leaving phase 1's health group in place would cap phase 2
            evs = ent["events"]["xrworks:completed_phase_transition"]["sequence"]
            evs.insert(0, {"remove": {"component_groups": [f"xrworks:hp_{i}" for i in range(len(HEALTH_STEPS))]}})
        dump(path, d)
    for path in (p for p in walk(os.path.join(BP, "entities")) if "/atk/" in p.replace(os.sep, "/")):
        kind = next((k for k in ROAR if k in os.path.basename(path)), None)
        if kind:
            edit(path, lambda d, kind=kind: d["minecraft:entity"]["components"]["minecraft:behavior.knockback_roar"]
                 .update(ROAR[kind]))


def walk(root, ext=".json"):
    for dirpath, _, names in os.walk(root):
        for n in sorted(names):
            if n.endswith(ext):
                yield os.path.join(dirpath, n)


DAMAGE = re.compile(r"^/damage @e\[type=!(xrworks:[a-z_]+),r=([\d.]+)\] (\d+) entity_attack entity @s$")


def fix_attacks():
    """/damage rings -> /scriptevent xrworks:hit <ring>; telegraph data per attack."""
    rings = {}
    for ident, info in BOSSES.items():
        path = os.path.join(BP, "animations", info["anim"] + ".animation.json")
        d = load(path)
        ent = load(os.path.join(BP, "entities", info["file"]))["minecraft:entity"]
        anim_ids = ent["description"]["animations"]
        attacks = {}
        for v in range(5):
            aid = anim_ids.get(f"atk_{v + 1}")
            an = d["animations"].get(aid)
            if not an:
                continue
            hits = []
            for t, cmds in list(an.get("timeline", {}).items()):
                cmds = cmds if isinstance(cmds, list) else [cmds]
                ring = sorted((float(m.group(2)), int(m.group(3))) for c in cmds if (m := DAMAGE.match(c)))
                if not ring:
                    continue
                key = f"{info['key']}_" + "_".join(f"{r:g}x{dmg}" for r, dmg in ring)
                rings[key] = [[r, RING_DAMAGE.get(dmg, max(2, round(dmg * 0.15)))] for r, dmg in ring]
                rest = [c for c in cmds if not DAMAGE.match(c)]
                an["timeline"][t] = rest + [f"/scriptevent xrworks:hit {key}"]
                hits.append({"t": round(float(t), 3), "r": ring[-1][0]})
            attacks[v] = sorted(hits, key=lambda h: h["t"])
        for an in d["animations"].values():  # Dr. Lantern's buff: Strength I, and only with "fury" on
            for t, cmds in an.get("timeline", {}).items():
                if isinstance(cmds, list):
                    an["timeline"][t] = [c.replace("strength infinite 1", "strength infinite 0") for c in cmds]
        info["attacks"] = attacks
        dump(path, d)
    return rings


def fix_scripts(rings):
    scripts = os.path.join(BP, "scripts")
    for name in ("fom_settings.js", "fom_combat.js", "fom_menu.js", "fom_seals.js"):
        shutil.copyfile(os.path.join(HERE, "fom", "scripts", name), os.path.join(scripts, name))
    data = {i: {k: v for k, v in info.items() if k in ("family", "color", "phase2Event", "width", "attacks")}
            for i, info in BOSSES.items()}
    write(os.path.join(scripts, "fom_data.js"),
          "// Generated by tools/fom_fix.py from the bosses' entities and attack animations.\n"
          f"export const BOSSES = {json.dumps(data)};\nexport const RINGS = {json.dumps(rings)};\n")
    master = os.path.join(scripts, "xrworks_bb_master.js")
    text = read(master)
    write(master, text.replace('import { system } from "@minecraft/server";',
                               'import { system } from "@minecraft/server";\n'
                               'import "./fom_combat.js";\nimport "./fom_menu.js";\nimport "./fom_seals.js";', 1))
    # knockback of the attacks on players and mobs: scaled by the setting
    for boss in ("blackbaron", "doctor_lantern"):
        path = os.path.join(scripts, "xrworks_mobs", f"xrmb_{boss}", f"xrworks_{boss}_kb.js")
        text = read(path)
        blocks = re.split(r"(?=\n\s*(?://[^\n]*\n\s*)?if \(entity\.typeId ===)", text)
        out = []
        for blk in blocks:
            if "excludeTypes" in blk:  # attacks on others (the lunges move the boss itself)
                blk = re.sub(r"t\.applyKnockback\(\s*\{\s*x:\s*([^,]+),\s*z:\s*([^}]+?)\s*\},\s*([\d.]+)\s*\)",
                             r"fomKnockback(t, { x: \1, z: \2 }, \3)", blk)
                blk = re.sub(r"t\.applyImpulse\(\{", "fomImpulse(t, {", blk)
            out.append(blk)
        text = 'import { fomKnockback, fomImpulse } from "../../fom_combat.js";\n' + "".join(out)
        if text.count("fomKnockback(t") != 3 or text.count("fomImpulse(t") != 3:
            sys.exit(f"{boss}_kb.js: no encontré los 3 empujes de ataque")
        write(path, text)
    path = os.path.join(scripts, "xrworks_mobs", "xrmb_blackbaron", "xrworks_blackbaron_botk.js")
    text = read(path)
    text = 'import { getSetting } from "../../fom_settings.js";\n' + text.replace(
        "system.runInterval(() => {\n", 'system.runInterval(() => {\n    if (!getSetting("baronRegen")) return;\n', 1)
    write(path, text)
    path = os.path.join(scripts, "xrworks_mobs", "xrmb_blackbaron", "xrworks_blackbaron_dmgre.js")
    text = read(path)
    text = 'import { getSetting } from "../../fom_settings.js";\n' + text.replace(
        "    const entity = event.hurtEntity;\n", '    if (!getSetting("baronArmor")) return;\n    const entity = event.hurtEntity;\n', 1)
    write(path, text)
    for name in ("xrworks_blackbaron_botk.js", "xrworks_blackbaron_dmgre.js"):
        if "getSetting(" not in read(os.path.join(scripts, "xrworks_mobs", "xrmb_blackbaron", name)).split("\n", 2)[2]:
            sys.exit(f"{name}: no pude añadir el ajuste")


