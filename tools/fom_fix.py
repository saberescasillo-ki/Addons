"""Rebalances Figures of Malice (SalletXR: The Black Baron and Dr. Lantern) and gives
each boss its own structure. Personal use: the output goes to the git-ignored
private/ folder.

    python3 tools/fom_fix.py path/to/FA.zip

Changes:
  * one-shot attacks: the attack animations ran /damage in three stacked rings
    (up to 140 + 56 + 19 at once, Dr. Lantern's every 0.04 s): now a script hit
    (tools/fom/scripts/fom_combat.js) with nerfed values, once per target every
    half second, x the damage setting and capped by "max hit". The melee hits are
    lowered too, and the launching knockback (17 blocks up) is far gentler;
  * the bosses no longer dig through blocks (a function cleared a 3x8x3 column
    around them every tick) nor break doors;
  * no natural spawning (the dormant statues had spawn rules);
  * a boss stuck at a step of up to 2 blocks climbs it;
  * particles mark the area of each attack while the boss winds it up;
  * settings menu, /xrworks:config: difficulty presets, health (also scaled by the
    number of players), damage, max hit, knockback, the Baron's regeneration and
    lightning armour, Dr. Lantern's phase-2 fury, telegraphs, climbing, permissions;
  * a structure for each boss (tools/fom/arenas.py), never generated by itself:
    /place structure xrworks:baron_citadel | xrworks:lantern_asylum, or
    /function xrworks/build_baron_citadel | xrworks/build_lantern_asylum.
    Their seal raises the boss's statue when a player comes near;
Fixes: sounds.json had an extra closing brace (the bosses' hurt and death sounds
were lost); the boss bar panel replaced the whole HUD panel (other packs' bars
vanished) and is now inserted into it; the script asked for the "beta" API.
"""
