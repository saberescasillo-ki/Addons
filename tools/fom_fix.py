def seal_texture(path, base, accent, glow):
    img = Image.new("RGBA", (16, 16), base + (255,))
    d = ImageDraw.Draw(img)
    d.rectangle((0, 0, 15, 15), outline=accent + (255,))
    d.rectangle((2, 2, 13, 13), outline=tuple(max(0, c - 30) for c in base) + (255,))
    d.ellipse((4, 4, 11, 11), outline=glow + (255,))
    d.line((7, 3, 8, 12), fill=glow + (255,))
    d.line((3, 7, 12, 8), fill=glow + (255,))
    img.save(path)


